-- İDXAL — qrup-qrup CURSOR ilə (hər qrup öz tranzaksiyasında)
-- ============================================================

BEGIN TRANSACTION;

DECLARE @BeyannameKey INT, @Tarix DATE, @IcraciIsciId INT, @TesdiqEdenIsciId INT, @TesdiqTarixi DATETIME2;
DECLARE @YeniId INT;
DECLARE @YaradilanBeyanname INT = 0, @YaradilanSetir INT = 0, @AtlananGrup INT = 0;

DECLARE qrup_cursor CURSOR LOCAL FAST_FORWARD FOR
    SELECT DISTINCT BeyannameKey, Tarix, IcraciIsciId, TesdiqEdenIsciId, TesdiqTarixi
    FROM #Kaynak
    ORDER BY Tarix, TesdiqTarixi;

OPEN qrup_cursor;
FETCH NEXT FROM qrup_cursor INTO @BeyannameKey, @Tarix, @IcraciIsciId, @TesdiqEdenIsciId, @TesdiqTarixi;

WHILE @@FETCH_STATUS = 0
BEGIN
    IF NOT EXISTS (SELECT 1 FROM KassaKursBeyannameleri
                   WHERE Tarix = @Tarix AND TesdiqTarixi = @TesdiqTarixi AND Silinib = 0)
    BEGIN
        INSERT INTO KassaKursBeyannameleri
            (Tarix, IcraciIsciId, Status, TesdiqEdenIsciId, TesdiqTarixi, ImtinaSebebi, YaradilmaTarixi, Silinib)
        VALUES
            (@Tarix, @IcraciIsciId, 2 /* Tesdiqlendi */, @TesdiqEdenIsciId, @TesdiqTarixi, NULL, @TesdiqTarixi, 0);

        SET @YeniId = SCOPE_IDENTITY();
        SET @YaradilanBeyanname = @YaradilanBeyanname + 1;

        INSERT INTO KassaKursSetirleri
            (BeyannameId, Valyuta, NagdAlis, NagdSatis, QeyriNagdAlis, QeyriNagdSatis, YaradilmaTarixi, Silinib)
        SELECT @YeniId, k.Valyuta, k.NagdAlis, k.NagdSatis, k.QeyriNagdAlis, k.QeyriNagdSatis, @TesdiqTarixi, 0
        FROM #Kaynak k
        WHERE k.BeyannameKey = @BeyannameKey;

        SET @YaradilanSetir = @YaradilanSetir + @@ROWCOUNT;
    END
    ELSE
    BEGIN
        SET @AtlananGrup = @AtlananGrup + 1;
    END

    FETCH NEXT FROM qrup_cursor INTO @BeyannameKey, @Tarix, @IcraciIsciId, @TesdiqEdenIsciId, @TesdiqTarixi;
END

CLOSE qrup_cursor;
DEALLOCATE qrup_cursor;

COMMIT TRANSACTION;

